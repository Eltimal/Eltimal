const { sleep, texts, findBtn, click } = require("./harness");
const P = require("./play"); const U = require("./util"); const { runAudience } = require("./court");
(async () => {
  const mode = process.argv[2] || "bien";
  const env = await U.career("a08_cycliste", +(process.argv[3] || 7));
  const { w, doc, CR, s, errors } = env;
  await U.untilLead(env, "a08_cycliste", 60);
  const cs = s.cases.a08_cycliste;
  console.log("lead", CR.fmtDate(s.day, "dow"), CR.fmtTime(s.min), "limite vidéo", CR.fmtDate(cs.vars.videoLimite));
  await P.openCase(w, doc, "Fournier");
  await P.runTask(w, doc, /Recevoir M. et Mme Fournier/);
  await P.runCall(w, doc, CR, { avoid: [/bu ou consommé/], advice: mode === "bien" ? [/Ne signez rien/, /factures/] : [/presque rien/] });
  await U.engageFee(env, cs, "Fournier");
  console.log("statut", cs.status, "trust", Math.round(cs.trust));
  const fresh = async () => { if (s.min > 15 * 60 || !CR.isBusinessDay(s.day)) { CR.endDay(s); while (!CR.isBusinessDay(s.day)) CR.endDay(s); } CR.store.bump(); await sleep(30); };
  if (mode === "lent") { for (let i = 0; i < 8; i++) CR.endDay(s); }
  await fresh(); await P.openCase(w, doc, "Fournier");
  console.log("tâches:", [...doc.querySelectorAll(".task strong")].map((x) => texts(x)).join(" | "));
  await P.runTask(w, doc, /Constituer les parents/);
  await P.fillDraft(w, doc, CR, cs, { key: "constitution_ji" });
  U.noteDocs(CR, s, cs);
  await P.openCase(w, doc, "Fournier");
  await P.runTask(w, doc, /demande d'actes/);
  await P.fillDraft(w, doc, CR, cs, { key: "demande_actes", check: [/vidéoprotection/, /accidentologique/, /livreur/, /prélèvement/] });
  console.log("actes envoyés", CR.fmtDate(cs.vars.demandeActesDay), "constituée", cs.proc.pcConstituee);
  await P.openCase(w, doc, "Fournier"); await P.runTask(w, doc, /copie du dossier/);
  await P.openCase(w, doc, "Fournier"); if (P.taskBtn(doc, /justificatifs/)) await P.runTask(w, doc, /justificatifs/);
  for (let i = 0; i < 20 && !CR.hasDoc(cs, "offre"); i++) CR.endDay(s);
  for (let i = 0; i < 3; i++) CR.endDay(s);
  console.log("offre", CR.hasDoc(cs, "offre"), "transaction", JSON.stringify(cs.vars.transaction));
  await fresh(); await P.openCase(w, doc, "Fournier");
  console.log("tâches:", [...doc.querySelectorAll(".task strong")].map((x) => texts(x)).join(" | "));
  if (P.taskBtn(doc, /Dénoncer/)) await P.runTask(w, doc, /Dénoncer/);
  U.noteDocs(CR, s, cs);
  CR.pinTexts(s, cs, ["L85_3", "JP_AP_1995", "CP_221-18", "CPP_475-1"]);
  await P.openCase(w, doc, "Fournier");
  if (P.taskBtn(doc, /offre de l'assureur/)) { await P.runTask(w, doc, /offre de l'assureur/); await P.fillDraft(w, doc, CR, cs, { key: "reponse_assureur", check: [/casque/, /proches/, /vitesse/] }); }
  console.log("réponse assureur", cs.vars.reponseAssureur);
  for (let i = 0; i < 200 && !cs.proc.audience; i++) CR.endDay(s);
  console.log("audience", cs.proc.audience && CR.fmtDate(cs.proc.audience.day, "dow"), "vidéo", cs.vars.videoOk, "perdue", cs.vars.videoPerdue, "tox", cs.vars.toxConfirmee, "aligné", cs.vars.assureurAligne);
  U.readAll(CR, s); U.noteDocs(CR, s, cs);
  await fresh(); await P.openCase(w, doc, "Fournier");
  await P.runTask(w, doc, /constitution de partie civile et le chiffrage/);
  await P.fillDraft(w, doc, CR, cs, { key: "constitution_pc", check: mode === "bien" ? [/sa mère/, /son père/, /frère/, /obsèques/, /475-1/] : [/sa mère/, /son père/, /économique/] });
  await P.openCase(w, doc, "Fournier"); if (P.taskBtn(doc, /Préparer M. et Mme/)) await P.runTask(w, doc, /Préparer M. et Mme/);
  while (s.day < cs.proc.audience.day) CR.endDay(s);
  CR.store.bump(); await sleep(30);
  await U.goCourt(env);
  const log = await runAudience(w, doc, CR, { questions: [/62 km/, /fumé/], args: mode === "bien" ? [/cause exclusive/, /1985/, /stupéfiants/, /affection/] : [/part de responsabilité/, /affection/] });
  console.log(log.join("\n"));
  await sleep(60);
  console.log("statut", cs.status, JSON.stringify(cs.outcome));
  console.log("débrief", JSON.stringify(cs.debrief && cs.debrief.items.map((i) => i.text.slice(0, 80))));
  console.log("erreurs dossier", JSON.stringify(cs.erreurs.map((e) => e.id)));
  console.log("errors:", errors.length ? errors.slice(0, 5).join("\n---\n") : "none");
  process.exit(0);
})().catch((e) => { console.error("FATAL", e); process.exit(1); });
