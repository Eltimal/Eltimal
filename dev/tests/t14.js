const { sleep, texts, findBtn, click } = require("./harness");
const P = require("./play"); const U = require("./util"); const { runAudience } = require("./court");
(async () => {
  const mode = process.argv[2] || "deonto";
  const env = await U.career("a12_bijouterie", +(process.argv[3] || 7));
  const { w, doc, CR, s, errors } = env;
  await U.untilRing(env, 100);
  console.log("sonnerie", CR.fmtDate(s.day, "dow"));
  await click(w, findBtn(doc, "Répondre"));
  await P.runCall(w, doc, CR, { advice: [/désigne/, /attestation/] });
  const cs = s.cases.a12_bijouterie;
  await U.engageFee(env, cs, "Leroy");
  console.log("statut", cs.status, "un an", CR.fmtDate(cs.vars.unAn), "prolong", CR.fmtDate(cs.vars.prolongDay));
  const T = "Leroy";
  const tasks = () => [...doc.querySelectorAll(".task strong")].map((x) => texts(x)).join(" | ");
  const fresh = async () => { if (s.min > 15 * 60 || !CR.isBusinessDay(s.day)) { CR.endDay(s); while (!CR.isBusinessDay(s.day)) CR.endDay(s); } CR.store.bump(); await sleep(30); };
  await P.openCase(w, doc, T); console.log("tâches:", tasks());
  await P.runTask(w, doc, /pour qu'il vous désigne/);
  for (const re of [/attestation d'hébergement/, /promesse d'embauche/]) { await P.openCase(w, doc, T); if (P.taskBtn(doc, re)) await P.runTask(w, doc, re); }
  for (let i = 0; i < 10 && !cs.flags.designe; i++) CR.endDay(s);
  await fresh(); await P.openCase(w, doc, T); console.log("désigné", CR.fmtDate(cs.flags.designe), "tâches:", tasks());
  await P.runTask(w, doc, /copie du dossier/);
  await P.openCase(w, doc, T); await P.runTask(w, doc, /permis de communiquer/);
  for (let i = 0; i < 8 && !cs.flags.permis; i++) CR.endDay(s);
  await fresh(); await P.openCase(w, doc, T);
  console.log("permis", cs.flags.permis, "tâches:", tasks());
  await P.runTask(w, doc, /parloir/);
  const avoid = mode === "kevin" ? [/aucun faux témoin/, /reconnaître/, /avant l'été/] : mode === "aveu" ? [/aucun faux témoin/, /citer Kevin/, /avant l'été/] : [/citer Kevin/, /reconnaître/, /avant l'été/];
  await P.runCall(w, doc, CR, { avoid });
  console.log("flags", JSON.stringify({ deonto: cs.flags.deontoOk, kevin: cs.flags.fauxTemoinPromis, reco: cs.flags.conseilReconnaitre }));
  U.readAll(CR, s); U.noteDocs(CR, s, cs);
  CR.pinTexts(s, cs, ["CPP_145-2", "CPP_144", "CP_132-75"]);
  const goH = async (re, o) => { const h = cs.hearings.find((x) => re.test(x.title) && !x.attended); if (!h) { console.log("pas d'audience", re); return; } while (s.day < h.day) CR.endDay(s); CR.store.bump(); await sleep(30); await U.goCourt(env); const log = await runAudience(w, doc, CR, o); console.log(h.title, "→", log.join(" / ").slice(0, 400)); };
  await goH(/prolongation/, { args: [/hébergement/, /raisonnable/, /ARSE/] });
  console.log("prolongation", cs.vars.prolongDecision, JSON.stringify(cs.proc.detention));
  for (let i = 0; i < 90 && !cs.vars.reunionDay; i++) CR.endDay(s);
  U.readAll(CR, s); U.noteDocs(CR, s, cs);
  await goH(/Réunion préparatoire/, { questions: mode === "kevin" ? [/Kevin/, /génétique/, /Roussel/] : [/Roussel/, /génétique/, /Martine/] });
  console.log("liste", JSON.stringify(cs.vars.liste), "erreurs", JSON.stringify(cs.erreurs.map((e) => e.id)));
  await fresh(); await P.openCase(w, doc, T); if (P.taskBtn(doc, /Préparer Jordan/)) await P.runTask(w, doc, /Préparer Jordan/);
  await goH(/Cour criminelle/, { questions: [/casque/], args: [/soixante-dix/, /transfert|déposé avant/, /reconnu/, /violence/, /Treize mois/], dernier: /pardon/ });
  await sleep(60);
  console.log("statut", cs.status, JSON.stringify(cs.outcome), "aveu", cs.flags.aveuAudience, "trust", Math.round(cs.trust), "prep", cs.flags.prepClient);
  console.log("débrief", JSON.stringify(cs.debrief && cs.debrief.items.slice(0, 7).map((i) => i.text.slice(0, 80))));
  console.log("errors:", errors.length ? errors.slice(0, 5).join("\n---\n") : "none");
  process.exit(0);
})().catch((e) => { console.error("FATAL", e); process.exit(1); });
