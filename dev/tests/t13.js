const { sleep, texts, findBtn, click } = require("./harness");
const P = require("./play"); const U = require("./util");
(async () => {
  const mode = process.argv[2] || "bien";
  const env = await U.career("a11_president", +(process.argv[3] || 7));
  const { w, doc, CR, s, errors } = env;
  await U.untilRing(env, 90);
  console.log("sonnerie", CR.fmtDate(s.day, "dow"), CR.fmtTime(s.min));
  await click(w, findBtn(doc, "Répondre"));
  await P.runCall(w, doc, CR, { avoid: [/rien vérifié/], advice: [/Ne supprimez/, /Relancez la banque/] });
  const cs = s.cases.a11_president;
  await U.engageFee(env, cs, "Rhône Usinage");
  console.log("statut", cs.status);
  await P.openCase(w, doc, "Rhône Usinage"); await P.runTask(w, doc, /Rassembler les pièces/);
  await P.openCase(w, doc, "Rhône Usinage"); await P.runTask(w, doc, /Appeler la banque/);
  U.noteDocs(CR, s, cs);
  CR.pinTexts(s, cs, ["CP_113-2-1", "CPP_382"]);
  if (mode === "lent") for (let i = 0; i < 5; i++) CR.endDay(s);
  CR.store.bump(); await sleep(30);
  await P.openCase(w, doc, "Rhône Usinage"); await P.runTask(w, doc, /Rédiger la plainte/);
  const dest = { bien: "Monsieur le procureur de la République près le tribunal judiciaire de Lyon", lent: "Monsieur le procureur de la République près le tribunal judiciaire de Lyon", paris: "Madame la procureure de la République près le tribunal judiciaire de Paris", doyen: "Monsieur le doyen des juges" }[mode];
  await P.fillDraft(w, doc, CR, cs, { key: "plainte_parquet", choose: { dest }, check: [/113-2-1/, /382/, /LT32/, /en-têtes/, /joints/] });
  console.log("plainte", JSON.stringify(cs.vars.plainte), "effective", cs.vars.plainteEffective, "gel", cs.vars.gel);
  for (let i = 0; i < 120 && cs.status !== "closed"; i++) CR.endDay(s);
  if (mode === "doyen") { CR.store.bump(); await sleep(30); console.log("tâches après irrecevabilité:", [...doc.querySelectorAll(".task strong")].map((x) => texts(x)).join(" | ")); }
  console.log("statut", cs.status, JSON.stringify(cs.outcome), "gel", cs.vars.gel);
  console.log("erreurs", JSON.stringify(cs.erreurs.map((e) => e.id)));
  console.log("errors:", errors.length ? errors.slice(0, 5).join("\n---\n") : "none");
  process.exit(0);
})().catch((e) => { console.error("FATAL", e); process.exit(1); });
