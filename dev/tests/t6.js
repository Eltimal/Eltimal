const { sleep, texts, findBtn, click } = require("./harness");
const P = require("./play"); const U = require("./util"); const { runAudience } = require("./court");
(async () => {
  const mode = process.argv[2] || "tp";
  const env = await U.career("a04_voisin");
  const { w, doc, CR, s, errors } = env;
  await U.untilLead(env, "a04_voisin");
  const cs = s.cases.a04_voisin;
  console.log("lead", cs.status, CR.fmtDate(s.day), "faits", CR.fmtDate(cs.proc.faitsDay), "presc", JSON.stringify(CR.PROC.prescription(cs)), CR.fmtDate(CR.PROC.prescription(cs).expire));
  await P.openCase(w, doc, "Diallo");
  await P.runTask(w, doc, /Recevoir M. Diallo/);
  await P.runCall(w, doc, CR, { avoid: [/prison/], advice: [/Apportez-moi/, /Évitez/] });
  await U.engageFee(env, cs, "Diallo");
  console.log("statut", cs.status, cs.fee && CR.offerShort(cs.fee));
  U.readAll(CR, s); U.noteDocs(CR, s, cs);
  await P.openCase(w, doc, "Diallo");
  await P.runTask(w, doc, /copie de la procédure classée/);
  const fresh = async () => { if (s.min > 15 * 60 || !CR.isBusinessDay(s.day)) { CR.endDay(s); while (!CR.isBusinessDay(s.day)) CR.endDay(s); } CR.store.bump(); await sleep(30); };
  await fresh();
  await P.openCase(w, doc, "Diallo");
  console.log("avant audiencement", CR.fmtDate(s.day), CR.fmtTime(s.min), s.at, "tâches:", [...doc.querySelectorAll(".task strong")].map((x) => texts(x)).join(" | "));
  await P.runTask(w, doc, /date d'audience/);
  console.log("toasts", JSON.stringify(s.toasts.map(t=>t.text)), CR.fmtTime(s.min), s.at);
  console.log("audiencement", CR.fmtDate(cs.vars.dateAudiencement, "dow"));
  for (let i = 0; i < 6 && !CR.hasDoc(cs, "pv_temoin_roux"); i++) CR.endDay(s);
  U.readAll(CR, s); U.noteDocs(CR, s, cs);
  while (!CR.isBusinessDay(s.day)) CR.endDay(s);
  CR.store.bump(); await sleep(40);
  await P.openCase(w, doc, "Diallo");
  await P.runTask(w, doc, /citation directe/);
  await P.fillDraft(w, doc, CR, cs, { key: "citation", choose: mode === "tc" ? { juridiction: "Tribunal correctionnel" } : {} });
  console.log("citation", JSON.stringify(CR.drafted(cs, "citation").defects));
  await fresh();
  await P.openCase(w, doc, "Diallo");
  await P.runTask(w, doc, /Déposer/);
  for (let i = 0; i < 6 && !(cs.vars.citation && cs.vars.citation.ctrl); i++) CR.endDay(s);
  console.log("délivrée", JSON.stringify(cs.vars.citation), "audience", cs.proc.audience && cs.proc.audience.juridiction, "stade", cs.proc.stade);
  U.readAll(CR, s);
  while (!CR.isBusinessDay(s.day)) CR.endDay(s);
  CR.store.bump(); await sleep(40);
  await P.openCase(w, doc, "Diallo");
  console.log("tâches:", [...doc.querySelectorAll(".task strong")].map((x) => texts(x)).join(" | "));
  if (P.taskBtn(doc, /consignation/)) await P.runTask(w, doc, /consignation/);
  await P.openCase(w, doc, "Diallo");
  await P.runTask(w, doc, /constitution de partie civile/);
  await P.fillDraft(w, doc, CR, cs, { key: "constitution_pc", check: [/Lunettes/, /Souffrances/, /moral/, /475-1/] });
  CR.pinTexts(s, cs, ["CPP_475-1", "CP_R625-1", "CPP_9-2"]);
  await P.openCase(w, doc, "Diallo");
  if (P.taskBtn(doc, /Préparer M. Diallo/)) await P.runTask(w, doc, /Préparer M. Diallo/);
  while (s.day < cs.proc.audience.day) CR.endDay(s);
  CR.store.bump(); await sleep(40);
  await U.goCourt(env);
  const log = await runAudience(w, doc, CR, { interject: true, questions: [/écarté de la main/, /Mme Roux/], args: [/Mme Roux/, /écarté/, /R. 625-1/, /lunettes/] });
  console.log(log.join("\n"));
  await sleep(100);
  console.log("statut", cs.status, JSON.stringify(cs.outcome), "consignation", JSON.stringify(cs.vars.consignation), "carpa", s.carpa);
  console.log("errors:", errors.length ? errors.slice(0, 5).join("\n---\n") : "none");
  process.exit(0);
})().catch((e) => { console.error("FATAL", e); process.exit(1); });
